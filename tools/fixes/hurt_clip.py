"""Destination wall checks and a swept head row during injury movement."""
from fixes.bug_descriptions import bug_fix


def emit(c):
    c.label("hurt_horizontal")
    c.emit("F5 D5 2A 26 C4 E5 C5 3A 20 C4 FE 05", "save af/de and original X/delta / test injury state")
    c.jr("hurt_horizontal_unchecked", "nz")
    c.emit("09 7C CB 78", "add hl,bc / ld a,h / bit 7,b")
    c.jr("hurt_horizontal_left", "nz")
    c.jr("hurt_horizontal_unchecked", "c")
    c.emit("FE F8", "cp 248 ; do not probe across an open edge")
    c.jr("hurt_horizontal_unchecked", "nc")
    c.emit("7C 32 27 C4", "temporarily use destination integer X")
    c.call(0x7BA9)
    c.jr("hurt_horizontal_checked")
    c.label("hurt_horizontal_left")
    c.jr("hurt_horizontal_unchecked", "nc")
    c.emit("FE 08", "cp 8")
    c.jr("hurt_horizontal_unchecked", "c")
    c.emit("7C 32 27 C4", "temporarily use destination integer X")
    c.call(0x7C05)
    c.label("hurt_horizontal_checked")
    c.emit("C1 E1 7C 32 27 C4", "restore delta and original X")
    c.jr("hurt_horizontal_done", "nc")
    c.emit("01 00 00", "ld bc,0 ; cancel blocked displacement")
    c.jr("hurt_horizontal_done")
    c.label("hurt_horizontal_unchecked")
    c.emit("C1 E1", "restore delta and original X")
    c.label("hurt_horizontal_done")
    c.emit("D1 F1 C9", "restore de and af / ret")

    c.label("hurt_vertical")
    c.emit("34 7E BA", "inc (hl) / ld a,(hl) / cp d")
    c.jr("hurt_vertical_index", "c")
    c.emit("7A", "ld a,d")
    c.label("hurt_vertical_index")
    c.emit("3D 60 69", "dec a / ld h,b / ld l,c")
    c.call(0x4061)
    c.emit("7E CB 7F", "ld a,(hl) / bit 7,a")
    c.jr("hurt_vertical_down", "z")
    c.emit("ED 44 47", "neg / ld b,a")
    c.label("hurt_vertical_up")
    c.emit("C5 3A 25 C4 D6 1B 5F", "save remaining steps / leading head row = feet - 27")
    c.call("hurt_head_solid")
    c.emit("C1 D8 3A 25 C4 3D 32 25 C4", "restore steps / stop at terrain / otherwise move up one pixel")
    c.branch(0x10, "hurt_vertical_up", "djnz", True)
    c.emit("C9", "ret")
    c.label("hurt_vertical_down")
    c.emit("3A 25 C4 86 32 25 C4 C9", "original downward displacement / ret")

    c.label("hurt_head_solid")
    c.emit("3A 27 C4 57", "ld a,($C427) / ld d,a")
    c.call(0x7D2F)
    c.call(0x7C5E)
    c.emit("D8 3A 27 C4 FE 07", "ret c / load center X / cp 7")
    c.jr("hurt_head_right", "c")
    c.emit("D6 07 57", "sub 7 / ld d,a")
    c.call(0x7D2F)
    c.call(0x7C5E)
    c.emit("D8", "ret c")
    c.label("hurt_head_right")
    c.emit("3A 27 C4 FE F9 D0 C6 07 57", "skip out-of-range right sample / add 7 / ld d,a")
    c.call(0x7D2F)
    c.jp(0x7C5E)


def apply(edit, hook, c):
    hook(0x2C94, "2A 26 C4", "hurt_horizontal", "Check the injury destination without changing ordinary motion")
    hook(0x2FE0, "CD 4D 6D", "hurt_vertical", "Sweep the leading head row only during injury ascent")


FIX = bug_fix("hurt_clip", emit_helpers=emit, apply=apply)
